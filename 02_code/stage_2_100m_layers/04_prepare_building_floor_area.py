"""Stage 2, step 4: raw building records to floor area by use.

Reads local Overture footprints, OpenBuildingMap occupancy and height codes,
land-use polygons and the height layer generated by step 02. Calls floor_area
and buildings.city_floor_area, then saves buildings/floor_area_by_use/<stem>.npz.
The fa array has shape (9, ny, nx): C1-C7, unknown use, and industrial floor area
already included in C2. Units are square metres per 100 m cell.

Large grids can be processed in horizontal strips; missing-storey medians are
then estimated within each strip. Use --global-sources for external row-group
indexes, concurrent workers and source access. See --help for each mode."""
from __future__ import annotations

import argparse
import gc
import json
import math
import sys
import time
import traceback
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import stage_1_data_inputs.configuration as configuration  # noqa: E402
from stage_2_100m_layers.building_sources.open_building_map_reader import Reader as OBMReader  # noqa: E402
from stage_2_100m_layers.building_sources.overture_reader import Reader as OvReader  # noqa: E402
from stage_2_100m_layers.buildings import city_floor_area, load_rules  # noqa: E402
from stage_2_100m_layers.cities import load_cities  # noqa: E402


def floor_area(row, ov, open_building_map, height, rules, mixed, strip_cells=None):
    """city_floor_area, in horizontal strips for large grids."""
    ny, nx = int(row["ny"]), int(row["nx"])
    k = 1 if not strip_cells else max(1, math.ceil(ny * nx / strip_cells))
    if k == 1:
        return city_floor_area(row, ov, open_building_map, height, rules, mixed)
    h = math.ceil(ny / k)
    cell = float(row.get("cell", 100.0))
    fa = np.zeros((9, ny, nx), np.float32)
    parts = []
    for i in range(k):
        r0, r1 = i * h, min(ny, (i + 1) * h)
        if r0 >= r1:
            break
        sub = dict(row); sub["y1"] = float(row["y1"]) - r0 * cell; sub["ny"] = r1 - r0
        f, st = city_floor_area(sub, ov, open_building_map, None if height is None else height[r0:r1], rules, mixed)
        fa[:, r0:r1] = f
        parts.append(st)
        del f
        gc.collect()
    nb = sum(st.get("buildings", 0) for st in parts)
    st = {"stem": row["stem"], "strips": len(parts), "buildings": nb}
    for key in ("read", "underground", "obm_buildings", "split_buildings", "footprint_km2", "gross_km2", "seconds"):
        st[key] = sum(p.get(key, 0) or 0 for p in parts)
    for key in ("share_obm", "share_own_class", "share_own_subtype", "share_land_use", "share_default", "share_aoi", "floors_known"):
        st[key] = sum((p.get(key) or 0) * p.get("buildings", 0) for p in parts) / max(nb, 1)
    st["gross_by_class_km2"] = [float(x) for x in fa.reshape(9, -1).sum(1) / 1e6]
    return fa, st


def global_main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--stems", nargs="*")
    ap.add_argument("--stems-file")
    ap.add_argument("--order", default="small", choices=["small", "large", "list"])
    ap.add_argument("--shard", default="0/1", help="k/n: process every n-th city starting at k")
    ap.add_argument("--reset-locks", action="store_true", help="remove <stem>.lock files left by killed workers")
    ap.add_argument("--overwrite", action="store_true", help="recompute cities that already have a floor-area file "
                    "(e.g. Chinese cities after s08 added Amap AOIs)")
    ap.add_argument("--strip-cells", type=int, default=500_000, help="process larger grids in strips (memory); 0: never")
    a = ap.parse_args(argv)
    c = load_cities()
    stems = list(a.stems or [])
    if a.stems_file:
        stems += [l.strip() for l in open(a.stems_file, encoding="utf-8") if l.strip()]
    if stems:
        c = c[c.stem.isin(stems)]
        if a.order == "list":                     # keep the order of the list
            c = c.set_index("stem").loc[[s for s in dict.fromkeys(stems) if s in set(c.stem)]].reset_index()
    if a.order != "list":
        c = c.assign(_n=c.nx * c.ny).sort_values("_n", ascending=(a.order == "small"))
    k, n = (int(x) for x in a.shard.split("/"))
    c = c.iloc[k::n]
    out = configuration.FLOOR_AREA; out.mkdir(parents=True, exist_ok=True)
    if a.reset_locks:
        for lk in out.glob("*.lock"):
            lk.unlink()
    ov = OvReader(configuration.SOURCE_INDEX / "overture_rowgroup_index_2026-10-21.0.parquet")
    open_building_map = OBMReader(configuration.SOURCE_INDEX / "obm_rowgroup_index.parquet")
    rules, mixed = load_rules()
    import os
    for row in c.to_dict("records"):
        f = out / f"{row['stem']}.npz"
        if f.exists() and not a.overwrite:
            continue
        lock = out / f"{row['stem']}.lock"          # several workers may run on the same list
        try:
            os.close(os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY))
        except FileExistsError:
            continue
        t0 = time.time()
        try:
            hp = configuration.ghsl_file("height", row['stem'])
            height = np.load(hp) if hp.exists() else None
            fa, st = floor_area(row, ov, open_building_map, height, rules, mixed, a.strip_cells or None)
            np.savez_compressed(out / f"{row['stem']}.tmp.npz", fa=fa)
            (out / f"{row['stem']}.tmp.npz").replace(f)
            st["height_layer"] = height is not None
        except Exception as e:
            st = {"stem": row["stem"], "error": repr(e), "trace": traceback.format_exc()[-1500:]}
        st["wall_s"] = round(time.time() - t0, 1)
        lock.unlink(missing_ok=True)
        with open(out / f"_stats_{k}of{n}.jsonl", "a", encoding="utf-8") as fh:
            fh.write(json.dumps(st) + "\n")
        print(json.dumps({x: st.get(x) for x in ("stem", "buildings", "share_obm", "share_land_use", "share_default", "wall_s", "error")}), flush=True)


def main(argv=None):
    arguments = list(sys.argv[1:] if argv is None else argv)
    if "--global-sources" in arguments:
        arguments.remove("--global-sources")
        return global_main(arguments)
    from stage_2_100m_layers.local_raw_preparation import run_step
    return run_step(4, arguments)


if __name__ == "__main__":
    main()
